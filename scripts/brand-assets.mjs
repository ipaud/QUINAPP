// Regenerates every brand asset from apps/api/src/lib/brand.mjs.
// Run after changing the symbol: `node scripts/brand-assets.mjs`
// Needs (macOS dev machine): rsvg-convert (brew install librsvg) and iconutil.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SYMBOL_PATHS, SYMBOL_VARIANTS, SYMBOL_VIEWBOX, BRAND_COLORS, symbolSvg, appTileSvg } from '../apps/api/src/lib/brand.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = (rel) => path.join(root, rel);
const rsvg = (svgPath, pngPath, size) => execFileSync('rsvg-convert', ['-w', String(size), '-h', String(size), svgPath, '-o', pngPath]);

// Web
mkdirSync(out('apps/web/brand'), { recursive: true });
for (const variant of Object.keys(SYMBOL_VARIANTS)) {
  writeFileSync(out(`apps/web/brand/quinapp-symbol${variant === 'principal' ? '' : `-${variant}`}.svg`), symbolSvg(variant));
}
rsvg(out('apps/web/brand/quinapp-symbol.svg'), out('apps/web/brand/favicon-32.png'), 32);
writeFileSync(out('build/icon-source.svg'), appTileSvg(1024));
rsvg(out('build/icon-source.svg'), out('apps/web/brand/apple-touch-icon.png'), 180);

// Desktop (electron-builder uses build/icon.png; icns for the macOS .app script)
rsvg(out('build/icon-source.svg'), out('build/icon.png'), 1024);
const iconset = out('build/icons.iconset');
for (const base of [16, 32, 64, 128, 256, 512]) {
  rsvg(out('build/icon-source.svg'), path.join(iconset, `icon_${base}x${base}.png`), base);
  if (base !== 64) rsvg(out('build/icon-source.svg'), path.join(iconset, `icon_${base}x${base}@2x.png`), base * 2);
}
rsvg(out('build/icon-source.svg'), path.join(iconset, 'icon_1024x1024.png'), 1024);
rmSync(out('build/icon.icns'), { force: true });
execFileSync('iconutil', ['-c', 'icns', iconset, '-o', out('build/icon.icns')]);

// Android adaptive icon: symbol inside the 66dp safe zone of the 108dp canvas.
const scale = (66 / SYMBOL_VIEWBOX).toFixed(4);
const androidPaths = SYMBOL_VARIANTS.principal
  .map(([key, color]) => `        <path android:fillColor="${color.toUpperCase()}" android:pathData="${SYMBOL_PATHS[key]}" />`)
  .join('\n');
writeFileSync(out('apps/android/app/src/main/res/drawable/ic_launcher_foreground.xml'), `<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- Generated by scripts/brand-assets.mjs. QuinApp Q-nota symbol in the 66dp safe zone. -->
    <group android:translateX="21" android:translateY="21" android:scaleX="${scale}" android:scaleY="${scale}">
${androidPaths}
    </group>
</vector>
`);
writeFileSync(out('apps/android/app/src/main/res/values/colors.xml'), `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${BRAND_COLORS.accent.toUpperCase()}</color>
</resources>
`);

console.log('Brand assets regenerated');
